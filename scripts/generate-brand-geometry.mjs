/**
 * Generates `core/brand/brandGeometry.generated.ts` from the canonical SVGs in `assets/brand/`.
 * Run after the icon or wordmark artwork changes: `pnpm brand:geometry`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { svgPathProperties } from "svg-path-properties";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SAMPLES = 72;
const CENTERLINE_BINS = 40;

function pathsFromSvg(file) {
  const svg = readFileSync(join(root, "assets/brand", file), "utf8");
  return [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].trim());
}

function splitSubpaths(d) {
  return d
    .split(/(?=M)/)
    .map((s) => s.trim())
    .filter(Boolean);
}

const round = (n) => Math.round(n * 10) / 10;

function measure(d, samples = SAMPLES) {
  const props = new svgPathProperties(d);
  const length = props.getTotalLength();
  const points = [];
  for (let i = 0; i < samples; i++) {
    const p = props.getPointAtLength((length * i) / (samples - 1));
    points.push(round(p.x), round(p.y));
  }
  return { length: round(length), points };
}

function bounds(ds) {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const d of ds) {
    const props = new svgPathProperties(d);
    const length = props.getTotalLength();
    for (let i = 0; i <= 600; i++) {
      const p = props.getPointAtLength((length * i) / 600);
      minX = Math.min(minX, p.x);
      minY = Math.min(minY, p.y);
      maxX = Math.max(maxX, p.x);
      maxY = Math.max(maxY, p.y);
    }
  }
  return { minX, minY, maxX, maxY };
}

/** Mid-line through a thin closed shape, left → right, for the smile sweep. */
function centerline(d) {
  const props = new svgPathProperties(d);
  const length = props.getTotalLength();
  const b = bounds([d]);
  const bins = Array.from({ length: CENTERLINE_BINS }, () => ({ min: Infinity, max: -Infinity }));
  for (let i = 0; i <= 1200; i++) {
    const p = props.getPointAtLength((length * i) / 1200);
    const t = (p.x - b.minX) / (b.maxX - b.minX);
    const bin = bins[Math.min(CENTERLINE_BINS - 1, Math.floor(t * CENTERLINE_BINS))];
    bin.min = Math.min(bin.min, p.y);
    bin.max = Math.max(bin.max, p.y);
  }
  const points = [];
  bins.forEach((bin, i) => {
    const x = b.minX + ((i + 0.5) / CENTERLINE_BINS) * (b.maxX - b.minX);
    points.push(round(x), round((bin.min + bin.max) / 2));
  });
  return { minX: round(b.minX), maxX: round(b.maxX), points };
}

const [primaryD, secondaryD, curveD] = pathsFromSvg("ansa_icon.svg");
const [secondaryRingD, lensD] = splitSubpaths(secondaryD);
const iconBounds = bounds([primaryD, secondaryD, curveD]);
const PAD = 6;
const iconViewBox = {
  x: round(iconBounds.minX - PAD),
  y: round(iconBounds.minY - PAD),
  w: round(iconBounds.maxX - iconBounds.minX + PAD * 2),
  h: round(iconBounds.maxY - iconBounds.minY + PAD * 2),
};

const [wordmarkD] = pathsFromSvg("ansa.svg");
const letters = splitSubpaths(wordmarkD).map((d) => ({ d, ...measure(d, 56) }));

const out = `/* eslint-disable */
// Generated by scripts/generate-brand-geometry.mjs — do not edit by hand.
// Source: assets/brand/ansa_icon.svg, assets/brand/ansa.svg

export type TracedPath = { d: string; length: number; points: number[] };

export const ICON_VIEW_BOX = ${JSON.stringify(iconViewBox)} as const;

export const ICON_PRIMARY: TracedPath = ${JSON.stringify({ d: primaryD, ...measure(primaryD) })};

export const ICON_SECONDARY_RING: TracedPath = ${JSON.stringify({ d: secondaryRingD, ...measure(secondaryRingD) })};

export const ICON_SECONDARY_LENS: TracedPath = ${JSON.stringify({ d: lensD, ...measure(lensD, 24) })};

export const ICON_CURVE = ${JSON.stringify({ d: curveD, ...centerline(curveD) })} as const;

export const WORDMARK_LETTERS: TracedPath[] = ${JSON.stringify(letters)};
`;

writeFileSync(join(root, "core/brand/brandGeometry.generated.ts"), out);
console.log("icon viewBox", iconViewBox, "letters", letters.map((l) => l.length));
